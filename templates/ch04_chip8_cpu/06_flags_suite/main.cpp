// --- the five flag-rule tasks, exercised directly ---

TEST(flags, carry_boundary_8xy4) {
    const uint8_t prog[] = {0x80, 0xE4};
    Chip8 c = mk(std::vector<uint8_t>(prog, prog + 2));
    c.v[0] = 0xFF; c.v[0xE] = 0x02;
    run(c, 1);
    EXPECT_EQ(c.v[0], 0x01);
    EXPECT_EQ(c.v[0xF], 1);
}

TEST(flags, borrow_direction_8xy5_vs_8xy7) {
    const uint8_t sub[] = {0x80, 0xE5};
    Chip8 a = mk(std::vector<uint8_t>(sub, sub + 2));
    a.v[0] = 3; a.v[0xE] = 5;
    run(a, 1);
    EXPECT_EQ(a.v[0], 0xFE);
    EXPECT_EQ(a.v[0xF], 0);          // borrow -> VF clear

    const uint8_t subn[] = {0x80, 0xE7};
    Chip8 b = mk(std::vector<uint8_t>(subn, subn + 2));
    b.v[0] = 3; b.v[0xE] = 5;
    run(b, 1);
    EXPECT_EQ(b.v[0], 0x02);
    EXPECT_EQ(b.v[0xF], 1);          // mirrored source, same "fit" semantics
}

// Both shift profiles must work AND disagree on the right operand.
TEST(flags, shift_source_quirk_both_settings) {
    const uint8_t shr[] = {0x83, 0x46};
    Chip8 modern = mk(std::vector<uint8_t>(shr, shr + 2));
    modern.v[3] = 0x82; modern.v[4] = 0x81;
    run(modern, 1);
    EXPECT_EQ(modern.v[3], 0x41);
    EXPECT_EQ(modern.v[0xF], 0);

    Chip8 cosmac = mk(std::vector<uint8_t>(shr, shr + 2));
    cosmac.v[3] = 0x82; cosmac.v[4] = 0x81;
    cosmac.quirks.shift_uses_vy = true;
    run(cosmac, 1);
    EXPECT_EQ(cosmac.v[3], 0x40);
    EXPECT_EQ(cosmac.v[0xF], 1);
}

TEST(flags, bcd_digit_order_fx33) {
    Chip8 c = mk({0xA4, 0x00, 0xF0, 0x33});
    c.v[0] = 205;
    run(c, 2);
    EXPECT_EQ(c.mem[0x400], 2);
    EXPECT_EQ(c.mem[0x401], 0);
    EXPECT_EQ(c.mem[0x402], 5);
}

TEST(flags, store_load_i_quirk_both_settings) {
    for (int modern = 0; modern <= 1; ++modern) {
        Chip8 c = mk({0xA5, 0x00, 0xFF, 0x55});
        c.quirks.load_store_leaves_i = modern != 0;
        c.v[2] = 0x9C;
        run(c, 2);
        EXPECT_EQ(c.mem[0x502], 0x9C);
        EXPECT_EQ(c.idx, modern ? 0x500 : 0x510);
    }
}

// --- integration: the committed flags suite program ---

TEST(flags_suite, runs_to_clean_halt) {
    Chip8 c = mk(kFlagsSuite);
    run(c, 200);
    EXPECT_TRUE(c.halted);
    EXPECT_EQ(c.illegal_op, 0x0000);   // ended via 0000, not a stray fault
}

TEST(flags_suite, final_state_matches_reference) {
    Chip8 c = mk(kFlagsSuite);
    run(c, 200);
    for (int r = 0; r < 16; ++r)
        EXPECT_EQ(c.v[r], kGoldenV[r]);
    EXPECT_EQ(c.idx, kGoldenI);
    EXPECT_EQ(c.cycles, kGoldenCycles);
}

// The same program must produce the SAME final state under both quirk
// profiles - it was written quirk-neutral on purpose (self-shifts, explicit
// I reloads, flag renormalization).
TEST(flags_suite, quirk_neutral_across_profiles) {
    Chip8 cosmac = mk(kFlagsSuite);
    run(cosmac, 200);

    Chip8 modern = mk(kFlagsSuite);
    modern.quirks.shift_uses_vy = true;
    modern.quirks.load_store_leaves_i = true;
    modern.quirks.vf_reset = true;
    modern.quirks.wrapping = false;
    run(modern, 200);

    for (int r = 0; r < 16; ++r)
        EXPECT_EQ(cosmac.v[r], modern.v[r]);
    EXPECT_EQ(cosmac.idx, modern.idx);
}
