// Golden final state of kFlagsSuite, produced by the reference solution
// (run twice, identical both times). See tests/public provenance. Regenerated
// values must be byte-identical; a mismatch here means a flag rule regressed.
constexpr uint8_t kGoldenV[16] = {0x00, 0x02, 0x01, 0x00, 0x01, 0xFF, 0xFF,
                                  0x00, 0x0A, 0x23, 0x02, 0x00, 0xCD, 0x03,
                                  0x42, 0x01};
constexpr uint16_t kGoldenI = 0x10F;
constexpr uint64_t kGoldenCycles = 40;

