// Challenge: run the course-original 8080 diagnostic (see CHALLENGE.md and
// tests/public/ch08_i8080_control_interrupts/roms/ch08_diag.asm.txt).
//
// The program drives CALL/RET, conditional jumps taken AND not-taken, the
// ALU matrix, and stores a combined checksum. Acceptance requires exact
// final registers, memory, and total T-states.

#define LABSTEST_MAIN
#include "labstest.hpp"

#include "cpu.hpp"

using namespace i8080;

namespace {

const std::vector<uint8_t> kDiag = {
    0x31, 0x00, 0x20, 0xCD, 0x30, 0x00, 0x47, 0xCD, 0x40, 0x00, 0x80, 0x32, 0x10, 0x40, 0x76, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3E, 0x88, 0xC6, 0x93, 0xC9, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3E, 0x07, 0xFE, 0x07, 0xC2, 0x55, 0x00, 0x3E, 0x01, 0xC3, 0x5A, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3E, 0x02, 0xC3, 0x5A, 0x00, 0xFE, 0x02, 0xC2, 0x66, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xC9
};

struct DiagRig {
    FlatBus bus;
    Cpu cpu;

    DiagRig() {
        // kDiag is the full 103-byte image: mainline plus both
        // subroutines at their fixed addresses (identical to the
        // committed tests/public fixture).
        for (size_t i = 0; i < kDiag.size(); ++i) bus.mem[i] = kDiag[i];
        cpu.bus = &bus;
        while (!cpu.halted && cpu.cycles < 10000) cpu.step();
    }
};

}  // namespace

TEST(diag, arithmetic_check_returns_carry_set_byte) {
    DiagRig rig;
    EXPECT_EQ(rig.bus.mem[0x0030 + 2], 0xC6);   // sanity: routine in place
    EXPECT_EQ(rig.cpu.b, 0x1B);                 // ADD path result via MOV B,A
}

TEST(diag, branch_matrix_takes_the_right_path) {
    DiagRig rig;
    EXPECT_EQ(rig.cpu.a, 0x1C);   // branch result 01 + B(1B)
    EXPECT_EQ(rig.bus.mem[0x4010], 0x1C);
}

TEST(diag, stack_balanced_and_exact_timing) {
    DiagRig rig;
    EXPECT_EQ(rig.cpu.sp, 0x2000);
    EXPECT_EQ(rig.cpu.cycles, 162u);
    EXPECT_TRUE(rig.cpu.halted);
}
